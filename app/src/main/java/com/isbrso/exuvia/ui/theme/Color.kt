 * separación visual sin romper la armonía.
 */
val ExuviaSurface = Color(0xFF30392B)

/*
 * Variante utilizada en contenedores secundarios,
 * incluyendo el fondo de la fotografía mientras carga.
 */
val ExuviaSurfaceVariant = Color(0xFF394332)

/*
 * Marrón principal utilizado en botones y elementos destacados.
 */
val ExuviaPrimary = Color(0xFF956640)

/*
 * Marrón más oscuro que puede utilizarse posteriormente
 * para estados presionados o elementos secundarios.
 */
val ExuviaPrimaryDark = Color(0xFF754C31)

/*
 * Texto claro utilizado sobre botones marrones.
 */
val ExuviaOnPrimary = Color(0xFFFFF3E4)

/*
 * Texto principal.
 *
 * Se utiliza un beige cálido en lugar de blanco puro
 * para reducir el contraste agresivo con el fondo oscuro.
 */
val ExuviaTextPrimary = Color(0xFFE8D4BE)

/*
 * Texto secundario para taxonomía, créditos
 * y elementos de menor jerarquía.
 */
val ExuviaTextSecondary = Color(0xFFC5A078)

/*
 * Color de bordes o divisores.
 */
val ExuviaOutline = Color(0xFF705A43)